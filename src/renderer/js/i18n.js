export function setLocale(next) {
  const v = next === 'en-US' || next === 'en' ? 'en-US' : 'zh-CN';
  if (v === locale) return;
  locale = v;
  document.documentElement.lang = v === 'en-US' ? 'en' : 'zh-CN';
  listeners.forEach((fn) => { try { fn(locale); } catch (e) { /* ignore */ } });
}

export function onLocale(fn) { listeners.add(fn); return () => listeners.delete(fn); }

/** t('中文原文', { n: 1 }) —— 英文环境查表替换，缺表回退原文 */
export function t(s, vars) {
  if (s == null) return s;
  let out = locale === 'en-US' ? (EN[s] !== undefined ? EN[s] : s) : s;
  if (vars) {
    for (const k of Object.keys(vars)) {
      out = out.split('{' + k + '}').join(String(vars[k]));
    }
  }
  return out;
}

